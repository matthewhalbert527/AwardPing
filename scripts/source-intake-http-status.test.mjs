import { readFileSync } from "node:fs";
import { runInNewContext } from "node:vm";
import ts from "typescript";
import { describe, expect, it, vi } from "vitest";
import { captureIntakePage, deterministicSourceIntakeReview, sourceIntakeCaptureDisposition } from "./lib/source-intake.mjs";

const good = { url: "https://example.edu/apply", title: "Example Fellowship",
  text: "Apply for the scholarship. Review eligibility and the application deadline.", contentType: "text/html" };

describe("HTTP failure classification before source-content relevance", () => {
  it.each([100, 199, 300, 301, 304, 400, 401, 403, 404, 408, 429, 500, 502, 503, 504, 599])(
    "keeps HTTP %s manual despite award/application words", (statusCode) => {
      const decision = deterministicSourceIntakeReview({ ...good, ok: false, statusCode });
      expect(decision).toMatchObject({ allowed: false, status: "needs_manual_review",
        reason: `http-status-${statusCode}`, qualityFlags: ["access-error", `http-status-${statusCode}`] });
      for (const mode of ["batch", "none"]) expect(sourceIntakeCaptureDisposition(decision, mode))
        .toEqual({ status: "needs_manual_review", status_reason: `http-status-${statusCode}` });
    },
  );
  it("reports the observed CloudFront403 instead of missing award signal", () => {
    const decision = deterministicSourceIntakeReview({ url: "https://example.edu/content", ok: false, statusCode: 403,
      title: "ERROR: The request could not be satisfied", text: "Request blocked. Generated by cloudfront.", contentType: "text/html" });
    expect(decision.reason).toBe("http-status-403");
    expect(decision.qualityFlags).toEqual(["access-error", "http-status-403"]);
  });
  it("does not let a contradictory ok=true override a non-success status", () => {
    expect(deterministicSourceIntakeReview({ ...good, ok: true, statusCode: 403 }).allowed).toBe(false);
  });
  it.each([undefined, null, 200])("respects explicit failed transport even with status %s", (statusCode) => {
    expect(deterministicSourceIntakeReview({ ...good, ok: false, statusCode }))
      .toMatchObject({ allowed: false, status: "needs_manual_review", reason: "access-error" });
  });
  it.each(["403", "200", 0, -1, 600, 200.5, NaN, Infinity, {}, [200]])("holds a malformed declared HTTP status %s", (statusCode) => {
    expect(deterministicSourceIntakeReview({ ...good, ok: true, statusCode }))
      .toMatchObject({ allowed: false, status: "needs_manual_review", reason: "invalid-http-status" });
  });
  it.each([200, 201, 204, 206, 299])("preserves ordinary content review for successful status %s", (statusCode) => {
    expect(deterministicSourceIntakeReview({ ...good, ok: true, statusCode })).toEqual(deterministicSourceIntakeReview(good));
  });
  it("preserves URL safety rejection, legacy missing-status behavior and 200 access-page detection", () => {
    expect(deterministicSourceIntakeReview({ ...good, url: "http://127.0.0.1/apply", statusCode: 403 }).status).toBe("rejected");
    expect(deterministicSourceIntakeReview(good)).toMatchObject({ allowed: true, status: "plausible" });
    expect(deterministicSourceIntakeReview({ ...good, statusCode: 200, ok: true, text: "Access denied" }))
      .toMatchObject({ allowed: false, status: "needs_manual_review", reason: "access-error" });
  });
});

// Evaluate the actual worker call expression, not a test-written forwarding
// shim. No worker entrypoint, database, retention, provider or network runs.
const workerUrl = new URL("./process-source-intake-requests.mjs", import.meta.url);
const workerAst = ts.createSourceFile(workerUrl.pathname, readFileSync(workerUrl, "utf8"), ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
const calls = [];
function visit(node) {
  if (ts.isCallExpression(node) && node.expression.getText(workerAst) === "deterministicSourceIntakeReview") calls.push(node);
  ts.forEachChild(node, visit);
}
visit(workerAst);

it("actual capture-to-review wiring carries HTTP metadata and never queues an access failure", async () => {
  expect(calls).toHaveLength(1);
  const fetchImpl = vi.fn(async () => new Response(
    "<html><head><title>ERROR: The request could not be satisfied</title></head><body>Scholarship applications unavailable</body></html>",
    { status: 403, headers: { "content-type": "text/html; charset=utf-8" } },
  ));
  const capture = await captureIntakePage(good.url, {
    fetchImpl, lookupImpl: async () => [{ address: "93.184.216.34", family: 4 }], dispatcherFactory: () => null,
  });
  expect(capture).toMatchObject({ ok: false, status_code: 403 });
  const decision = runInNewContext(calls[0].getText(workerAst), {
    deterministicSourceIntakeReview, capture, normalizedUrl: good.url, row: { award_name: "Example Fellowship" },
  });
  expect(decision).toMatchObject({ allowed: false, status: "needs_manual_review", reason: "http-status-403" });
  expect(sourceIntakeCaptureDisposition(decision, "batch").status).toBe("needs_manual_review");
  expect(fetchImpl).toHaveBeenCalledTimes(1); // Mock transport only; no retry added.
});
